"""Writes the content manifest into the Character Intake project from vault-registry.json:
  - Index.html: a compact `const CONTENT` (status per class / subclass / species / background) between /*content:start*/ and /*content:end*/
  - Data_ContentManifest.js: the full manifest with vault paths (server side, tests)
and fails if the form's DATA lists something the manifest does not classify (so a new item can never appear unreviewed).
Usage: python wire_manifest.py [clasp dir]"""
import json, re, os, sys, datetime

HERE = os.path.dirname(os.path.abspath(__file__))
CLASP = sys.argv[1] if len(sys.argv) > 1 else "B:/New folder/Second Brain.vault/_Agent-Only/code/kadria-appscript"
assert "plugin" + " test" not in CLASP.lower(), "the old plugin test vault is retired; the Intake code lives in the Kadria appscript repo"
reg = json.load(open(os.path.join(HERE, "vault-registry.json"), encoding="utf8"))["entries"]
man = json.load(open(os.path.join(HERE, "content-manifest.json"), encoding="utf8"))
html = open(f"{CLASP}/Index.html", encoding="utf8", newline="").read()
NL = "\r\n" if "\r\n" in html else "\n"
m = re.search(r"const DATA = (\{.*\});?\r?\n", html)
DATA = json.loads(m.group(1))

content = {"generated": datetime.date.today().isoformat(), "classes": {}, "subclasses": {}, "species": {}, "backgrounds": {}}
for e in reg:
    ed = e.get("edition", "")
    if e["type"] == "class": content["classes"][e["name"]] = e["status"]
    elif e["type"] == "subclass": content["subclasses"].setdefault(e["parent"], {})[f'{e["name"]}|{ed}'] = e["status"]
    elif e["type"] == "species": content["species"][f'{e["name"]}|{ed}'] = e["status"]
    elif e["type"] == "background": content["backgrounds"][f'{e["name"]}|{ed}'] = e["status"]

# every item the form can offer must be classified exactly once
missing = []
for c in DATA["classes"]:
    if c not in content["classes"]: missing.append(("class", c))
    for s in DATA["subclasses"].get(c, []):
        if f'{s["name"]}|{s["edition"]}' not in content["subclasses"].get(c, {}): missing.append(("subclass", c, s["name"], s["edition"]))
for ed in ("2024", "2014"):
    for n in DATA["species"][ed]:
        if f"{n}|{ed}" not in content["species"]: missing.append(("species", n, ed))
    for n in DATA["backgrounds"][ed]:
        if f"{n}|{ed}" not in content["backgrounds"]: missing.append(("background", n, ed))
if missing:
    print("UNCLASSIFIED in form DATA:", len(missing))
    for x in missing[:30]: print("  ", x)
    sys.exit(1)

blob = "/*content:start*/const CONTENT = " + json.dumps(content, separators=(",", ":"), ensure_ascii=False) + ";/*content:end*/"
if "/*content:start*/" in html:
    html = re.sub(r"/\*content:start\*/.*?/\*content:end\*/", lambda _: blob, html, flags=re.S)
else:
    html = html.replace(m.group(0), m.group(0) + "    " + blob + NL, 1)
open(f"{CLASP}/Index.html", "w", encoding="utf8", newline="").write(html)

full = dict(man)
full["generated"] = datetime.date.today().isoformat()
full["entries"] = [{k: e[k] for k in ("type", "parent", "name", "edition", "status", "path") if k in e} for e in reg]
js = ("/**\n * Kadria Character Intake - content manifest, generated by sim/audit/wire_manifest.py from the Kadria vault registry.\n"
      " * status: main | unverified | legacy | pending | quarantine | removed | double. `path` is the note under C:/Kadria.vault/Books.\n"
      " * The form reads only the compact CONTENT copy inside Index.html; this file is the full record for the server and tests.\n */\n"
      "var KADRIA_CONTENT_MANIFEST = " + json.dumps(full, ensure_ascii=False) + ";\n")
open(f"{CLASP}/Data_ContentManifest.js", "w", encoding="utf8", newline="").write(js)

print("wired. classes", len(content["classes"]), "| subclasses", sum(len(v) for v in content["subclasses"].values()),
      "| species", len(content["species"]), "| backgrounds", len(content["backgrounds"]), "| Index.html +", len(blob), "bytes")
